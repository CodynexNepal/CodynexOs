import fs from 'fs';
import path from 'path';

const UUID_REGEX = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const PREVIEWS_ROOT = path.resolve(process.cwd(), 'previews');

function escapeHtml(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

export class PreviewDeployService {
  private ensureProjectDir(projectId: string): string {
    if (!UUID_REGEX.test(projectId)) {
      throw new Error('Invalid project ID for preview storage.');
    }
    const dir = path.join(PREVIEWS_ROOT, projectId);
    fs.mkdirSync(dir, { recursive: true });
    return dir;
  }

  savePreview(projectId: string, htmlContent: string) {
    const dir = this.ensureProjectDir(projectId);
    const filePath = path.join(dir, 'index.html');
    fs.writeFileSync(filePath, htmlContent, 'utf8');
    return {
      filePath,
      previewUrl: `/preview/${projectId}`,
      liveUrl: `/live/${projectId}`,
    };
  }

  readPreview(projectId: string): string | null {
    if (!UUID_REGEX.test(projectId)) return null;
    const filePath = path.join(PREVIEWS_ROOT, projectId, 'index.html');
    if (!fs.existsSync(filePath)) return null;
    return fs.readFileSync(filePath, 'utf8');
  }

  buildFallbackUiHtml(params: {
    projectTitle: string;
    instruction: string;
    summary?: string;
    sections?: Array<{ title?: string; description?: string }>;
  }): string {
    const title = escapeHtml(params.projectTitle || 'CodyNex Live App');
    const summary = escapeHtml(
      params.summary ||
        'Generated by CodyNex OS UI/UX Department and verified across Frontend, Backend, QA, and DevOps.',
    );
    const instruction = escapeHtml(params.instruction);
    const sections =
      Array.isArray(params.sections) && params.sections.length > 0
        ? params.sections
        : [
            { title: 'Hero & Value Proposition', description: instruction },
            { title: 'Core Interactive Workspace', description: 'Live operational controls, metrics, and responsive layout.' },
            { title: 'API & Data Integration', description: 'Connected to CodyNex OS Backend & PostgreSQL.' },
          ];

    const cardsHtml = sections
      .slice(0, 6)
      .map(
        (s, idx) => `
      <div style="background:#FFFFFF;border:1px solid #E4E4E0;border-radius:12px;padding:20px;">
        <div style="display:inline-block;background:#EAFCCB;color:#14532D;border:1px solid #9FE870;border-radius:999px;padding:2px 10px;font-size:11px;font-weight:700;margin-bottom:10px;">Module ${idx + 1}</div>
        <h3 style="margin:0 0 8px;font-size:16px;font-weight:700;color:#0E0F0C;">${escapeHtml(s.title || `Section ${idx + 1}`)}</h3>
        <p style="margin:0;font-size:13px;line-height:1.55;color:#5A5D57;">${escapeHtml(s.description || '')}</p>
      </div>`,
      )
      .join('\n');

    return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width,initial-scale=1" />
  <title>${title} — CodyNex Live Preview</title>
</head>
<body style="margin:0;background:#F7F7F5;color:#0E0F0C;font-family:Inter,system-ui,-apple-system,sans-serif;">
  <header style="background:#0E0F0C;color:#FFFFFF;padding:16px 28px;display:flex;align-items:center;justify-content:space-between;flex-wrap:wrap;gap:12px;">
    <div style="display:flex;align-items:center;gap:10px;">
      <span style="display:inline-flex;align-items:center;justify-content:center;width:32px;height:32px;border-radius:8px;background:#9FE870;color:#0E0F0C;font-weight:800;font-size:13px;">CN</span>
      <div>
        <div style="font-weight:700;font-size:15px;">${title}</div>
        <div style="font-size:11px;color:#A1A49E;">Built by CodyNex OS Autonomous Company</div>
      </div>
    </div>
    <span style="background:#163300;color:#C3FF7D;border:1px solid #2F5D14;padding:4px 12px;border-radius:999px;font-size:11px;font-weight:700;">LIVE PREVIEW</span>
  </header>

  <main style="max-width:1080px;margin:0 auto;padding:36px 24px;">
    <section style="background:#FFFFFF;border:1px solid #E4E4E0;border-radius:16px;padding:32px;margin-bottom:24px;">
      <p style="margin:0 0 8px;font-size:11px;font-weight:700;text-transform:uppercase;letter-spacing:0.08em;color:#14532D;">UI/UX Prototype Ready</p>
      <h1 style="margin:0 0 12px;font-size:28px;font-weight:800;line-height:1.2;">${title}</h1>
      <p style="margin:0 0 20px;font-size:15px;line-height:1.6;color:#5A5D57;">${summary}</p>
      <div style="display:flex;flex-wrap:wrap;gap:10px;">
        <button onclick="document.getElementById('status-msg').textContent='Interactive UI verified — ready for Frontend, Backend, QA & DevOps handoff.'" style="background:#9FE870;color:#0E0F0C;border:none;border-radius:8px;padding:10px 18px;font-size:13px;font-weight:700;cursor:pointer;">Test Primary Action</button>
        <span id="status-msg" style="align-self:center;font-size:12px;color:#14532D;font-weight:600;"></span>
      </div>
    </section>

    <section style="display:grid;grid-template-columns:repeat(auto-fit,minmax(260px,1fr));gap:16px;">
      ${cardsHtml}
    </section>
  </main>
</body>
</html>`;
  }
}

export const previewDeployService = new PreviewDeployService();
